#!/usr/bin/env python3
"""Validation study for the CFD pipeline (see documentation/research/04-toolchain-and-cfd-method.md).

  1. builds the validation duct geometry (make_validation_geometry.py) into <workdir>/validation_geom
  2. writes validation_case.json there (also kept in this folder for reference)
  3. runs: (a) fixed flow-rate inlet at mesh levels 1,2,3   (mesh sensitivity)
           (b) fanPressure inlet (example linear 300 Pa / 4e-3 m3/s curve) at level 2
  4. collects validation_summary.json + selected PNGs into ./results/
  5. then run plot_mesh_study.py for the GCI table / plot (results/mesh_study.*)

Usage: /opt/k1th/venv/bin/python run_validation.py [--workdir DIR] [--levels 1,2,3] [--np 4] [--only a|b]
"""
import argparse
import json
import math
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PIPE = HERE.parent / "pipeline"
sys.path.insert(0, str(PIPE))
sys.path.insert(0, str(HERE))
import run_case  # noqa: E402
from make_validation_geometry import main as make_geom  # noqa: E402


def centerline():
    pts = [[42.5, 0, 35.0], [42.5, 0, 20.5]]
    for k in range(1, 19):                       # bend, radius 12.5 about (30, 20.5)
        th = -math.pi / 2 * k / 18
        pts.append([30 + 12.5 * math.cos(th), 0, 20.5 + 12.5 * math.sin(th)])
    pts += [[10.0, 0, 1.5], [3.6, 0, 1.5]]       # contraction centre line -> slot -> nozzle face
    return [[round(c, 4) for c in p] for p in pts]


def config(fan_csv):
    return {
        "name": "validation",
        "stl_dir": ".",
        "surfaces": {
            "duct": {"file": "duct.stl", "type": "wall", "level": [3, 3], "feature_level": 3},
            "nozzle": {"file": "nozzle.stl", "type": "wall", "level": [4, 4], "feature_level": 4},
            "inlet": {"file": "inlet.stl", "type": "inlet", "level": [3, 3],
                      "bc": {"kind": "flowRate", "Q_m3_s": 4.5e-4}},
        },
        "domain": {"min": [-45, -30, -15], "max": [60, 30, 45], "cell_mm": 3.2, "patches": {}},
        "location_in_mesh": [-20.0, 0.1, -10.0],
        "refinement_boxes": [
            {"name": "wake", "min": [-20, -16, -8], "max": [20, 16, 10], "level": 2},
            {"name": "jet", "min": [-8, -12, -3], "max": [14, 12, 5], "level": 3},
            {"name": "slot", "min": [6, -10.6, 0.0], "max": [14, 10.6, 3.0], "level": 4},
        ],
        "probes": {
            "planes": [
                {"name": "slot_exit", "type": "rect", "origin": [10.2, 0, 1.5], "normal": [-1, 0, 0],
                 "u": [0, 1, 0], "half": [10.5, 1.4], "ds_mm": 0.05},
                {"name": "tip_annulus", "type": "annulus", "origin": [0, 0, -0.5], "normal": [0, 0, 1],
                 "u": [1, 0, 0], "r_in": 0.0, "r_out": 5.0, "sectors": 8},
            ],
            "points": [{"name": "lidar_line", "xyz": [-36, -21, -0.5]},
                       {"name": "below_tip_1mm", "xyz": [0, 0, -1.0]},
                       {"name": "nozzle_front", "xyz": [3.6, 0, 1.5]}],
            "lines": [{"name": "duct_centerline", "points": centerline()}],
        },
        "loss_pairs": [["inlet", "slot_exit"]],
        "plots": {"slices": [
            {"name": "y0", "axis": "y", "value": 0.0, "range": [[-15, 55], [-8, 42]]},
            {"name": "tip_z-0.5", "axis": "z", "value": -0.5, "range": [[-40, 20], [-25, 25]]}],
            "streamlines": True, "azimuth": -60},
        "fluid": {"nu": 1.6e-5, "rho": 1.16},
        "mesh": {"n_between": 2},
        "solver": {"max_iter": 1500},
        "_fan_csv": "pipeline/fans/" + Path(fan_csv).name,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workdir", default=run_case.DEFAULT_WORKDIR)
    ap.add_argument("--levels", default="1,2,3")
    ap.add_argument("--np", type=int, default=4)
    ap.add_argument("--only", choices=["a", "b"])
    a = ap.parse_args()
    work = Path(a.workdir)
    gdir = work / "validation_geom"
    make_geom(gdir)
    fan_csv = PIPE / "fans/example_linear_300Pa.csv"
    cfg = config(fan_csv)
    (gdir / "validation_case.json").write_text(json.dumps(cfg, indent=2))
    ref = dict(cfg, stl_dir="<workdir>/validation_geom (generated by make_validation_geometry.py)")
    (HERE / "validation_case.json").write_text(json.dumps(ref, indent=2))

    runs = []
    if a.only in (None, "a"):
        for L in [int(x) for x in a.levels.split(",")]:
            runs.append((f"val_flowrate_L{L}", L, []))
    if a.only in (None, "b"):
        runs.append(("val_fan_L2", 2, ['surfaces.inlet.bc={"kind":"fan","csv":"%s"}' % fan_csv]))
    summary = {}
    for name, L, sets in runs:
        case = run_case.main([str(gdir / "validation_case.json"), "--level", str(L), "--name", name,
                              "--workdir", str(work), "--np", str(a.np)] + sum((["--set", s] for s in sets), []))
        r = json.loads((case / "results/results.json").read_text())
        summary[name] = r
        out = HERE / "results" / name
        out.mkdir(parents=True, exist_ok=True)
        shutil.copy(case / "results/results.json", out / "results.json")
        if name == "val_fan_L2":   # keep the repo light: PNGs only for the fan case (full set stays in workdir)
            for png in ("slice_y0_Umag.png", "slice_tip_z-0.5_Umag.png", "convergence.png",
                        "line_duct_centerline.png"):
                if (case / "results" / png).exists():
                    shutil.copy(case / "results" / png, out / png)
    old = HERE / "results/validation_summary.json"
    allres = json.loads(old.read_text()) if old.exists() else {}
    allres.update({k: {"cells": v["mesh"]["cells"], "timing_s": v["timing_s"],
                       "converged": v["convergence"]["converged"],
                       "iterations": v["convergence"]["iterations"],
                       "Q_inlet_m3_s": v["inlets"]["inlet"]["Q_m3_s"],
                       "p_total_inlet_Pa": v["inlets"]["inlet"]["p_total_avg_Pa"],
                       "slot_U_mean_flux": v["planes"]["slot_exit"].get("Umag_mean_flux"),
                       "slot_Q": v["planes"]["slot_exit"].get("Q_through_m3_s"),
                       "annulus_Umag_mean": v["planes"]["tip_annulus"].get("Umag_mean_area"),
                       "annulus_symmetry_min_over_max": v["planes"]["tip_annulus"].get("symmetry_min_over_max"),
                       "dp_total_inlet_to_slot_Pa": v["losses"].get("inlet->slot_exit", {}).get("dp_total_Pa"),
                       "nozzle_wss_mean_Pa": v["walls"].get("nozzle", {}).get("wss_mean_Pa"),
                       "lidar_Umag": v["points"]["lidar_line"]["Umag"]}
                   for k, v in summary.items()})
    old.write_text(json.dumps(allres, indent=2))
    print(json.dumps(allres, indent=1))


if __name__ == "__main__":
    main()
